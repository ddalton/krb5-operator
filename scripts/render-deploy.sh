#!/usr/bin/env bash
# Render deploy/operator.yaml (plain manifests, for kubectl apply) from the
# Helm chart, so there is one source. CI fails when it is stale.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "# Generated by scripts/render-deploy.sh from charts/krb5-operator: do not edit."
  echo "# The operator in namespace krb5-operator. Apply deploy/crds.yaml first."
  echo "apiVersion: v1"
  echo "kind: Namespace"
  echo "metadata:"
  echo "  name: krb5-operator"
  helm template krb5-operator "$ROOT/charts/krb5-operator" --namespace krb5-operator
} >"$ROOT/deploy/operator.yaml"
